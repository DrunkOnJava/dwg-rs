//! ACAD_GROUP object (spec §19.6.7 — L6-11) — named, ordered set of
//! entity handles.
//!
//! Groups are user-visible selection sets exposed via the GROUP
//! command. They behave like a loose collection: members retain
//! their own ownership (block record, layout) but the group holds
//! soft-pointer references to them.
//!
//! # Stream shape — measured
//!
//! ```text
//! TV      name                  -- group description; empty in practice
//! BS      unnamed               -- non-zero for AutoCAD-generated "*A" groups
//! BS      selectable            -- non-zero if selecting a member selects all
//! BL      num_members
//! ```
//!
//! The member handles are handle references, not data-stream fields, so
//! they are not read here; the *i*-th of them is the *i*-th member.
//!
//! An earlier cut read `B unnamed, B selectable` and then the handles
//! inline. Both GROUP records of `sample_AC1032.dwg` (handles 1430 and
//! 1437) say otherwise: each leaves exactly 30 bits between the end of
//! its common object data and the start of its string stream, spent as
//! three 10-bit fields — `BS` = 2, `BS` = 1, `BL` = 6 — with the name
//! in the string stream. Two single-bit flags plus a `BL` cannot fill
//! 30 bits, and reading them that way runs the `BL` off the end of the
//! record, which is what made both records fail to decode.
//!
//! The first field reading 2 rather than the 0/1 a boolean would
//! suggest is why it is surfaced as a raw [`i16`]: the width is
//! established by the bytes, the semantics of that particular value are
//! not, and this crate has no second file with a GROUP record to
//! cross-check against.
//!
//! The `num_members` count is capped at 100 000 per spec-safety
//! guidance: real drawings rarely exceed a few hundred group
//! members, and an unbounded count from an adversarial file would
//! otherwise allow a decompression-bomb-adjacent allocation vector.

use crate::bitcursor::BitCursor;
use crate::error::{Error, Result};
use crate::objects::modern;
use crate::string_stream::StringReader;
use crate::version::Version;

/// Maximum GROUP member handle count honored by the decoder.
const MAX_GROUP_HANDLES: usize = 100_000;

/// Decoded ACAD_GROUP body.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct AcadGroup {
    pub name: String,
    /// Raw `BS`; non-zero on AutoCAD-generated `*A…` groups. See the
    /// module docs on why this is not a `bool`.
    pub unnamed: i16,
    /// Raw `BS`; non-zero when selecting one member selects the group.
    pub selectable: i16,
    /// How many member handles follow the data stream. The handles
    /// themselves are handle references, not data-stream fields.
    pub num_members: u32,
}

impl AcadGroup {
    /// Was this group generated by AutoCAD rather than named by a user?
    pub fn is_unnamed(&self) -> bool {
        self.unnamed != 0
    }

    /// Does selecting one member select the whole group?
    pub fn is_selectable(&self) -> bool {
        self.selectable != 0
    }
}

/// Read the ACAD_GROUP field list from whichever streams hold it.
fn read_body(
    c: &mut BitCursor<'_>,
    strings: &mut Option<StringReader<'_>>,
    version: Version,
) -> Result<AcadGroup> {
    let name = modern::read_tv(c, strings, version)?;
    let unnamed = c.read_bs()?;
    let selectable = c.read_bs()?;
    let num_members = c.read_bl()? as usize;
    if num_members > MAX_GROUP_HANDLES {
        return Err(Error::SectionMap(format!(
            "ACAD_GROUP claims {num_members} member handles (>{MAX_GROUP_HANDLES} sanity cap)"
        )));
    }
    Ok(AcadGroup {
        name,
        unnamed,
        selectable,
        num_members: num_members as u32,
    })
}

/// Decodes the `AcadGroup` payload that follows the common object header.
pub fn decode(c: &mut BitCursor<'_>, version: Version) -> Result<AcadGroup> {
    read_body(c, &mut None, version)
}

/// Decode an ACAD_GROUP straight from its raw object payload, taking
/// the group name from the R2007+ string stream when the file has one
/// and checking the data fields end exactly on the data-stream
/// boundary.
pub(crate) fn decode_object(
    payload: &[u8],
    body_start: usize,
    inline_data_end: Option<usize>,
    version: Version,
) -> Result<AcadGroup> {
    let mut split = modern::open(payload, body_start, inline_data_end, version)?;
    let out = read_body(&mut split.data, &mut split.strings, version)?;
    split.finish("ACAD_GROUP")?;
    Ok(out)
}
